  await expect(panel).toHaveCount(0); await page.getByRole('button', { name: '选择', exact: true }).click(); expect(await current(page)).toEqual(previous);
  await page.getByRole('button', { name: '添加入口', exact: true }).last().click(); await page.getByTestId('facilities-item-' + secondId).click();
  await expect(panel).toHaveCount(0); await expect(page.getByRole('dialog')).toHaveCount(0); expect(await current(page)).toEqual(previous);
