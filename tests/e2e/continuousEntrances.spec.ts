    expect(access.name).toBe('入口' + String(index + 1).padStart(3, '0')); expect(access.facilityId).toBe(facilityId);
    const position = next.nodes[access.nodeId]!.position; positions.push(position);
    expect(Math.abs((position[0] - a[0]) * dy - (position[1] - a[1]) * dx) / length).toBeLessThan(1e-7);
    expect(Math.hypot(position[0] - midpoint[0], position[1] - midpoint[1])).toBeLessThanOrEqual(2 / at.scale);
    expect(next.roads).toEqual(base.roads); expect(next.facilities[facilityId]!.boundary).toEqual(base.facilities[facilityId]!.boundary);
    expect(next.facilities[secondId]).toEqual(base.facilities[secondId]); expect(next.servicePoints).toEqual(base.servicePoints); expect(next.resources).toEqual(base.resources);
    for (const [nodeId, node] of Object.entries(previous.nodes)) expect(next.nodes[nodeId]).toEqual(node);
    expect(next.revision).toBe(previous.revision + 1);
    await page.getByRole('button', { name: '撤销', exact: true }).click(); expect(await current(page)).toEqual(previous); await expect(panel).toBeVisible();
