    const midpoint: Vec3 = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2, 0], at = await expectVisiblePosition(page, midpoint);
    // The outer ring is counterclockwise; move four CSS pixels to its exterior side.
    const x = at.x + 4 * dy / length, y = at.y + 4 * dx / length;
